// Authoring helper only. The generated asset is committed for static/no-build hosting.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const templateFiles = ['propfirm.html', 'plan.html', 'tradesim.html', 'mental.html']
  .map(name => `src/modules/study-hub/presentation/templates/${name}`);
const outputFile = 'src/modules/study-hub/presentation/study-hub-template.js';

function renderTemplate(parts) {
  if (parts.length !== templateFiles.length) throw new Error('Expected four StudyHub HTML fragments');
  if (parts.some(part => !part.endsWith('\n'))) throw new Error('HTML source files must end with LF');
  // Strip each editorial final LF; preserve the original two-LF module separators.
  const html = parts.map(part => part.slice(0, -1)).join('\n\n');
  const literals = html.split('\n').map(line => '  ' + JSON.stringify(line)
    .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029'));
  return '// Generated by scripts/build-study-hub-template.cjs; edit presentation/templates/*.html.\n' +
    'globalThis.TradeDiaryStudyHubTemplate = [\n' + literals.join(',\n') + '\n].join("\\n");\n';
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/build-study-hub-template.cjs [--check]');
    const generated = renderTemplate(templateFiles.map(file => fs.readFileSync(path.join(root, file), 'utf8')));
    const target = path.join(root, outputFile);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
        throw new Error('StudyHub template asset is stale; run node scripts/build-study-hub-template.cjs');
      }
      console.log('PASS: StudyHub template asset matches HTML sources');
    } else {
      fs.writeFileSync(target, generated);
      console.log(`Generated ${outputFile}`);
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = {templateFiles, outputFile, renderTemplate};
